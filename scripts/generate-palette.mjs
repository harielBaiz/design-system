/**
 * Generates the raw colour palette: `src/tokens/palette.css` and `src/tokens/palette.ts`.
 * Run: node scripts/generate-palette.mjs
 *
 * Every hue shares the same lightness per step (OKLCH), so a step means the same thing in every hue:
 * 500 and 600 are mid tones, 50–200 are tints, 800–950 are shades. Chroma follows a smooth curve
 * and is reduced where the sRGB gamut cannot hold it. The palette has no meaning yet: map steps to
 * semantic tokens in tokens.css instead of using these directly in components.
 */
import { writeFileSync } from 'node:fs';

const STEPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
const L = { 50: 0.975, 100: 0.945, 200: 0.89, 300: 0.82, 400: 0.74, 500: 0.65, 600: 0.56, 700: 0.47, 800: 0.38, 900: 0.3, 950: 0.22 };
// name, OKLCH hue angle, peak chroma
const HUES = [
  ['red', 27, 0.21], ['orange', 52, 0.18], ['amber', 78, 0.17], ['yellow', 98, 0.17], ['lime', 125, 0.19], ['green', 150, 0.18],
  ['teal', 183, 0.12], ['cyan', 215, 0.12], ['blue', 255, 0.19], ['indigo', 275, 0.2], ['purple', 305, 0.2], ['magenta', 340, 0.21],
];

const lin = (c) => (c <= 0.0031308 ? 12.92 * c : 1.055 * Math.pow(c, 1 / 2.4) - 0.055);
function oklchToRgb(l, c, hDeg) {
  const h = (hDeg * Math.PI) / 180, a = c * Math.cos(h), b = c * Math.sin(h);
  const l_ = l + 0.3963377774 * a + 0.2158037573 * b, m_ = l - 0.1055613458 * a - 0.0638541728 * b, s_ = l - 0.0894841775 * a - 1.291485548 * b;
  const L3 = l_ ** 3, M3 = m_ ** 3, S3 = s_ ** 3;
  return [
    lin(4.0767416621 * L3 - 3.3077115913 * M3 + 0.2309699292 * S3),
    lin(-1.2684380046 * L3 + 2.6097574011 * M3 - 0.3413193965 * S3),
    lin(-0.0041960863 * L3 - 0.7034186147 * M3 + 1.707614701 * S3),
  ];
}
const inGamut = (rgb) => rgb.every((v) => v >= -0.0001 && v <= 1.0001);
function hex(l, c, h) {
  let lo = 0, hi = c, rgb = oklchToRgb(l, c, h);
  if (!inGamut(rgb)) {
    for (let i = 0; i < 30; i++) { const mid = (lo + hi) / 2; if (inGamut(oklchToRgb(l, mid, h))) lo = mid; else hi = mid; }
    rgb = oklchToRgb(l, lo, h);
  }
  return '#' + rgb.map((v) => Math.round(Math.min(1, Math.max(0, v)) * 255).toString(16).padStart(2, '0')).join('');
}
// chroma curve: strongest in the mid tones, soft at the tints and the shades
const chroma = (peak, l) => Math.max(0.015, peak * (1 - Math.pow((l - 0.62) / 0.5, 2)));

const palette = {};
for (const [name, h, peak] of HUES) {
  palette[name] = {};
  for (const s of STEPS) palette[name][s] = hex(L[s], chroma(peak, L[s]), h);
}

let css = `/*\n * Raw colour palette (generated by scripts/generate-palette.mjs, do not edit by hand).\n * No semantic meaning yet: components must not use these directly.\n * Map a step to a semantic token in tokens.css when a colour gets a job.\n */\n:root {\n`;
for (const [name] of HUES) {
  css += `  /* ${name} */\n  ` + STEPS.map((s) => `--color-${name}-${s}: ${palette[name][s]};`).join(' ') + '\n';
}
css += '}\n';
writeFileSync('src/tokens/palette.css', css);

const ts = `// Generated by scripts/generate-palette.mjs. Do not edit by hand.
export const PALETTE_STEPS = ${JSON.stringify(STEPS)} as const;
export type PaletteStep = (typeof PALETTE_STEPS)[number];
export const PALETTE: Record<string, Record<PaletteStep, string>> = ${JSON.stringify(palette, null, 2)};
export const PALETTE_HUES = ${JSON.stringify(HUES.map((h) => h[0]))} as const;
`;
writeFileSync('src/tokens/palette.ts', ts);
console.log('hues', HUES.length, 'steps', STEPS.length);
for (const [name] of HUES) console.log(name.padEnd(8), STEPS.map((s) => palette[name][s]).join(' '));
